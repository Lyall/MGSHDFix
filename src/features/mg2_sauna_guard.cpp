    constexpr uint64_t nOriginalGuardHash = 0x0BCFCCB17C814335ull;
    constexpr int nGuardImageEntry = 52;
    SafetyHookMid s_hDrawSprite;

    constexpr uint16_t nOrbGlyph = 56;
    constexpr size_t nMaxOrbRecords = 64;
    constexpr size_t nSeekOffsetOnStack = 0x44;
    constexpr uint16_t nSingleTrack = 1;
    constexpr uint16_t nSingleRecord = 1;
    constexpr uint16_t nOrbCycleTicks = 96;
    constexpr int nMSXTicks = 2;
    constexpr int nMCTicks = 3;
    constexpr int nOrbXOffset = -7;
    constexpr int nOrbYOffset = -18;
    constexpr std::array<int, 16> anOrbWobble = { 0, 0, 0, 0, 1, 1, 2, 2, 3, 4, 5, 5, 6, 6, 7, 7 };
    bool s_bOrbShown = false;

    int OrbWobble(int nCounter)
    {
        const int nStep = nCounter & 31;
        return anOrbWobble[nStep < 16 ? nStep : 31 - nStep];
    }

    void RestoreOrbRecords(SafetyHookContext& stContext)
    {
        if (!MG2_SpritePatcher::IsPatched(nGuardImageEntry))
        {
            return;
        }

        auto* pSprite = reinterpret_cast<Sprite*>(stContext.rsi);
        if (pSprite->nSheet != MG2_SPRITE_SHEET_GUARD)
        {
            return;
        }

        if (pSprite->nAnim != MG2_GUARD_ANIMATION_CENSOR_ORB)
        {
            // The guard draws before his orb, including when hidden.
            s_bOrbShown = pSprite->nShown && (pSprite->nAnim == MG2_GUARD_ANIMATION_WALK_UP || pSprite->nAnim == MG2_GUARD_ANIMATION_WALK_DOWN);
            return;
        }

        pSprite->nShown = s_bOrbShown;
        s_bOrbShown = false;

        uint8_t* pSheet = reinterpret_cast<uint8_t*>(stContext.rbp);
        const uint32_t nAnimation = *reinterpret_cast<const uint32_t*>(stContext.rsp + nSeekOffsetOnStack);
        if (Memory::ReadBE16(pSheet + nAnimation + nAnimationTrackCountOffset) != nSingleTrack)
        {
            return;
        }

        const size_t nCount = Memory::ReadBE16(pSheet + nAnimation + nAnimationFirstRecordCountOffset);
        if (nCount == 0 || nCount > nMaxOrbRecords)
        {
            return;
        }

        // 64 MSX steps over 96 MC ticks.
        Memory::WriteBE16(pSheet + nAnimation + nAnimationFirstRecordCountOffset, nSingleRecord);
        uint8_t* pRecord = pSheet + nAnimation + nAnimationFirstRecordOffset;
        const int nCounter = pSprite->nTime * nMSXTicks / nMCTicks;
        Memory::WriteBE16(pRecord + nAnimationRecordGlyphOffset, nOrbGlyph);
        Memory::WriteBE16(pRecord + nAnimationRecordXOffset, static_cast<uint16_t>(OrbWobble(nCounter) + nOrbXOffset));
        Memory::WriteBE16(pRecord + nAnimationRecordYOffset, static_cast<uint16_t>(OrbWobble(nCounter >> 1) + nOrbYOffset));
        Memory::WriteBE16(pRecord + nAnimationRecordDurationOffset, nOrbCycleTicks);
    }
